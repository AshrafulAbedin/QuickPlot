export type EquationType =
  | 'cartesian'
  | 'polar'
  | 'parametric'
  | 'implicit'
  | 'points'

export interface EquationEntry {
  id: string
  type: EquationType
  expression: string
  expressionY?: string
  tMin: number
  tMax: number
  color: string
  visible: boolean
  showDerivative?: boolean
  points?: Array<{ x: number; y: number }>
}

export interface ViewportState {
  xMin: number
  xMax: number
  yMin: number
  yMax: number
}

export interface SliderConfig {
  name: string
  value: number
  min: number
  max: number
  step: number
}

export interface CanvasTheme {
  name: string
  bg: string
  gridColor: string
  axisColor: string
  textColor: string
}

// ── Persistence ────────────────────────────────────────────────────────────
// Mirrors supabase/migrations. Column names are snake_case in Postgres and
// mapped to these camelCase fields in apps/2d/src/lib/workspaces-supabase.ts.

/** Bump when the shape of equations/viewport/sliders/theme changes; old rows keep their version so a loader can migrate them. */
export const WORKSPACE_SCHEMA_VERSION = 1

/** public.profiles — one row per auth user, created by a DB trigger. */
export interface UserProfile {
  id: string
  displayName: string | null
  avatarUrl: string | null
  createdAt: string
  updatedAt: string
}

export type WorkspaceRole = 'viewer' | 'editor'

/** public.workspace_collaborators */
export interface WorkspaceCollaborator {
  workspaceId: string
  userId: string
  role: WorkspaceRole
  createdAt: string
  /** Joined from profiles when listed. */
  profile?: Pick<UserProfile, 'displayName' | 'avatarUrl'>
}

/** public.workspaces */
export interface Workspace {
  id: string
  ownerId: string
  title: string
  description: string | null
  schemaVersion: number
  equations: EquationEntry[]
  viewport: ViewportState
  sliders: SliderConfig[]
  theme?: CanvasTheme
  /** When true anyone holding `shareToken` can read the workspace. */
  isPublic: boolean
  /** Always present (generated by the DB); only useful while `isPublic`. */
  shareToken: string
  createdAt: string
  updatedAt: string
  lastOpenedAt: string | null
}

/** `ownerId` is intentionally absent — the database fills it from the session. */
export type CreateWorkspaceInput =
  Pick<Workspace, 'title' | 'equations' | 'viewport' | 'sliders'> &
  Partial<Pick<Workspace, 'description' | 'theme' | 'isPublic'>>

export type UpdateWorkspaceInput =
  Partial<Pick<Workspace, 'title' | 'description' | 'equations' | 'viewport' | 'sliders' | 'theme' | 'isPublic'>>
